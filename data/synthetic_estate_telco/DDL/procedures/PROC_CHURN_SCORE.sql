-- PROCEDURE: PROC_CHURN_SCORE
-- LANGUAGE: PL/SQL
-- TYPE: transform
-- READS: DW_TELCO.CDR_FACT, DW_TELCO.TICKET_FACT
-- WRITES: DW_TELCO.CHURN_SCORE
-- CALLS: NONE
-- HAS_DYNAMIC: False
-- HAS_CURSOR: True
-- COMPLEXITY: high
CREATE OR REPLACE PROCEDURE PROC_CHURN_SCORE AS
BEGIN
    CURSOR c IS SELECT * FROM DW.FACT_ORDERS;
    BEGIN FOR rec IN c LOOP NULL; END LOOP; END;
END PROC_CHURN_SCORE;
/
