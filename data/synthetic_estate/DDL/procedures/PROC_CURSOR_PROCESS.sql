-- PROCEDURE: PROC_CURSOR_PROCESS
-- LANGUAGE: PL/SQL
-- TYPE: transform
-- READS: DW.FACT_ORDERS
-- WRITES: DW.BRANCH_PERF
-- CALLS: NONE
-- HAS_DYNAMIC: False
-- HAS_CURSOR: True
-- COMPLEXITY: high
CREATE OR REPLACE PROCEDURE PROC_CURSOR_PROCESS AS
BEGIN
    CURSOR c IS SELECT * FROM DW.FACT_ORDERS;
    BEGIN FOR rec IN c LOOP NULL; END LOOP; END;
END PROC_CURSOR_PROCESS;
/
