-- PROCEDURE: PROC_DYNAMIC_RISK
-- LANGUAGE: PL/SQL
-- TYPE: transform
-- READS: DW.RISK_EXPOSURE
-- WRITES: VW_DYNAMIC_RISK
-- CALLS: NONE
-- HAS_DYNAMIC: True
-- HAS_CURSOR: False
-- COMPLEXITY: high
CREATE OR REPLACE PROCEDURE PROC_DYNAMIC_RISK AS
BEGIN
    EXECUTE IMMEDIATE 'SELECT * FROM ' || v_table || ' WHERE RUN_DATE = ''' || p_run_date || '''';
END PROC_DYNAMIC_RISK;
/
