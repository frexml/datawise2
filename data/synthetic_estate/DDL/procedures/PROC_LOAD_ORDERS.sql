-- PROCEDURE: PROC_LOAD_ORDERS
-- LANGUAGE: PL/SQL
-- TYPE: load
-- READS: SAP_ORDERS, SAP_PRODUCT
-- WRITES: DW.FACT_ORDERS, DW.ORDER_LINE
-- CALLS: NONE
