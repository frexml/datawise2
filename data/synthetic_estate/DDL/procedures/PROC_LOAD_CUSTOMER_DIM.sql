-- PROCEDURE: PROC_LOAD_CUSTOMER_DIM
-- LANGUAGE: PL/SQL
-- TYPE: load
-- READS: SAP_CUSTOMER, STG_CUSTOMER
-- WRITES: DW.CUSTOMER_DIM
-- CALLS: NONE
-- HAS_DYNAMIC: False
-- HAS_CURSOR: False
-- COMPLEXITY: medium
CREATE OR REPLACE PROCEDURE PROC_LOAD_CUSTOMER_DIM AS
BEGIN
    INSERT INTO DW.CUSTOMER_DIM SELECT * FROM SAP_CUSTOMER;
END PROC_LOAD_CUSTOMER_DIM;
/
